#!/usr/bin/env python3
"""Fortune Cookie Funnies for Engineers — writes one fortune to /output/entry.txt.

Candidates considered (all original, fortune + twist, judged on the brief's
criteria: real fortune cookie for an engineer, punchline lands on first read,
fresh — no mug/slide stock — tight, funniest word last):

1. You will finally understand the legacy code. The author has just resigned.
2. You will receive praise for your elegant code today. It was generated by AI.
3. A bug you fixed months ago will return today. It missed you.
4. You will deploy on Friday and go home early. Your pager has other plans.
5. Your code will pass every test today. The tests were written by you.
6. Your standup update will take thirty seconds. The meeting will take
   forty-five minutes.
7. Great wealth awaits you in production. It is a log full of warnings you ignored.

Chosen: #2. It is a declarative fortune ("You will receive praise..."),
its twist lives in the engineer's world (elegant code, AI generation), the
surprise is fresh for 2026 rather than a recycled mug joke, and the funniest
word — "AI" — sits at the very end.
"""

import os

ENTRY = "You will receive praise for your elegant code today. It was generated by AI."

assert 1 <= len(ENTRY) <= 120, "entry must be 1-120 characters"
assert "\n" not in ENTRY and "\r" not in ENTRY, "entry must be a single line"
assert ENTRY.strip(), "entry must not be only whitespace"


def main() -> None:
    out_dir = os.environ.get("OUTPUT_DIR", "/output")
    os.makedirs(out_dir, exist_ok=True)
    path = os.path.join(out_dir, "entry.txt")
    with open(path, "w", encoding="utf-8") as f:
        f.write(ENTRY)
    # Read back and verify the gate exactly: 1-120 chars, one line, no
    # trailing newline, UTF-8.
    with open(path, "rb") as f:
        raw = f.read()
    assert raw == ENTRY.encode("utf-8"), "entry.txt bytes differ from ENTRY"
    assert not raw.endswith(b"\n"), "no trailing newline allowed"


if __name__ == "__main__":
    main()
